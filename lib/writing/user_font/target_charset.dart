  // ── 数字与英文 ─────────────────────────────────────────────────────
  static const String digits = '0123456789';
  static const String fullWidthDigits = '０１２３４５６７８９';
  static const String asciiLetters =
      'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz';

  // ── 常用标点（全角为主）────────────────────────────────────────────
  static const String punctuation =
      '，。！？；：""''（）【】《》〈〉「」『』、…——·~·'
      '—～·‧·，。！？；：""''（）【】《》、…—～'
      ',.!?;:()[]<>/\\@#\$%^&*-+=_|`\'"~';

  // ── 汇总所有目标字符（去重） ─────────────────────────────────────
  static final Set<String> all = _buildSet();

  static Set<String> _buildSet() {
    final buf = StringBuffer();
    buf.write(_commonChinese);
    buf.write(_commonChinese2);
    buf.write(digits);
    buf.write(fullWidthDigits);
    buf.write(asciiLetters);
    buf.write(punctuation);
    // 常见汉字补充（CJK 常用区 3500 字核心段）
    for (int cp = 0x4E00; cp <= 0x4E2F; cp++) {
      buf.writeCharCode(cp);
    }
    // 将字符串拆分为单个字形单元
    final result = <String>{};
    for (final ch in buf.toString().characters) {
      if (ch.trim().isNotEmpty) result.add(ch);
    }
    return result;
  }

  /// 判断某字符是否在目标范围内
  static bool contains(String ch) => all.contains(ch);

  /// 将字符串过滤为仅保留目标字符
  static String filter(String text) =>
      text.characters.where(contains).join();
}
